"""Prepare a bounded, traceable Stack v2 Edu code pilot outside the repository.

This is a pilot builder, not a global fork detector or production corpus build.
It reads only pinned, SHA256-verified local gzip shards from a download manifest.
Source text is data: it is never imported, compiled, or executed.
"""
